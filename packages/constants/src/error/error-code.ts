// =================================================================
// 1. 错误码结构设计 (Error Code Structure)
// =================================================================
// 采用 A-BB-CCC 七位数字编码规则：
//
// A (第1位): 错误来源大类
//    - 1: 客户端,发起方错误 (如参数错误、权限不足)
//    - 2: 服务端,接受端内部错误 (如数据库异常、代码逻辑崩溃)
//    - 3: 跨服务依赖调用错误 (内部 RPC/DO 调用失败、第三方接口超时等；跨越了本服务执行边界)
//
// BB (第2-3位): 服务模块标识
//    - 00: 通用模块
//    - 01: API网关 (Transport & Auth)
//
// CCC (第4-6位): 具体错误明细
//    - 001-999: 具体的业务异常编号
// =================================================================

// =================================================================
// 2.系统级错误码分类 (Global Standard Codes)
// =================================================================
// 100400  : INVALID_ARGUMENT   - 基础参数校验失败 (原 400)
// 100401  : UNAUTHORIZED       - 登录态失效 (原 401)
// 100403  : PERMISSION_DENIED  - 权限不足 (原 403)
// 100429  : RATE_LIMIT_EXCEEDED- 客户端触发限流 (原 429)
// 200500  : INTERNAL_SERVER_ERROR - 系统内部崩溃 (原 500)
// 200503  : SERVICE_UNAVAILABLE   - 服务过载/熔断 (原 503)
// =================================================================

// =================================================================
// 3. 业务错误码示例 - 应用层 (Business Logic Codes)
// =================================================================

// --- 用户模块 (Module 02) ---
// 102001  : USER_NOT_FOUND       - 用户账户不存在
// 102002  : PASSWORD_WRONG       - 登录密码错误
// 102003  : ACCOUNT_FROZEN       - 账号已被封禁/锁定
// 102004  : PHONE_VERIFY_FAILED  - 手机验证码不匹配
// =================================================================

export const errorCode = {
	// =================================================================
	// 100xxx: 通用客户端错误 (BB=00) - 对应业务层通用异常
	// =================================================================
	INVALID_ARGUMENT: 100400, // 参数校验失败
	UNAUTHORIZED: 100401, // 通用未授权 (如 JWT 失效)
	PERMISSION_DENIED: 100403, // 权限不足
	RATE_LIMIT_EXCEEDED: 100429, // 触发限流

	// =================================================================
	// 101xxx: 通信鉴权错误 (BB=01, A=1) - 由调用方(Caller)引起
	// =================================================================
	AUTH_INTERNAL_MISSING: 101001, // 缺少内部通信签名头
	AUTH_INTERNAL_EXPIRED: 101002, // 内部请求时间戳过期 (防重放)
	AUTH_INTERNAL_SIG_ERROR: 101003, // 内部签名验证不匹配
	AUTH_USER_ID_MISSING: 101004, // 上游未透传用户 ID
	AUTH_BEARER_ERROR: 101005, // Bearer 凭证缺失、无效或内容不完整
	AUTH_CONNECT_TOKEN_ERROR: 101006, // WebSocket connect token 缺失、无效或与房间不匹配

	// =================================================================
	// 200xxx: 通用服务端错误 (BB=00) - 对应代码崩溃/环境问题
	// =================================================================
	INTERNAL_SERVER_ERROR: 200500, // 通用内部错误
	SERVICE_UNAVAILABLE: 200503, // 服务不可用
};
